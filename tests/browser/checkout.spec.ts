import { test, expect } from '@playwright/test';

test('checkout calculates area fees and validates independent delivery details', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/');
  await page.locator('.date-strip button').nth(1).click();
  await page.getByRole('button', { name: 'Breakfast', exact: true }).click();
  await page.getByRole('button', { name: 'Add Smoky jollof rice', exact: true }).click();
  await page.getByRole('button', { name: 'Continue to extras' }).click();
  await page.getByRole('button', { name: /Add to cart/ }).click();
  await page.getByRole('complementary').getByRole('button', { name: 'Review your order' }).click();
  await page.getByRole('link', { name: 'Continue to checkout' }).click();
  await expect(page.getByRole('heading', { name: 'Make it yours.' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Continue to sign in' })).toBeDisabled();
  await page.getByRole('radio', { name: '9:00–10:00 AM' }).check();
  await page.getByLabel('Delivery area').selectOption('samaru');
  await page.getByLabel('Address & landmark').fill('Samaru, beside the main market entrance');
  await expect(page.locator('.checkout-total')).toContainText('2,200');
  await page.getByLabel('Use sample wallet credit').check();
  await expect(page.locator('.checkout-total')).toContainText('700');
  await page.getByLabel('Delivery & payment email').fill('amina@example.com');
  await page.getByRole('button', { name: 'Continue to sign in' }).click();
  await page.screenshot({ path: 'test-results/mealhr-signin-phone.png' });
  await page.getByLabel('Phone number', { exact: true }).fill('123');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('11-digit');
  await page.getByLabel('Phone number', { exact: true }).fill('08031234567');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/mealhr-signin-code-mobile.png' });
  await page.getByLabel('Verification code', { exact: true }).fill('000000');
  await page.getByRole('button', { name: 'Verify preview code' }).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('doesn’t match');
  await page.getByLabel('Verification code', { exact: true }).fill('123456');
  await page.getByRole('button', { name: 'Verify preview code' }).click();
  await page.screenshot({ path: 'test-results/mealhr-signin-name-mobile.png' });
  await page.getByLabel('Your name', { exact: true }).fill('Amina Yusuf');
  await page.getByRole('button', { name: 'Continue to checkout', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Thanks, Amina Yusuf');
  await expect(page.getByLabel('Address & landmark')).toHaveValue('Samaru, beside the main market entrance');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/mealhr-checkout-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/mealhr-checkout-mobile.png', fullPage: true });
  await page.getByRole('button', { name: /^Pay / }).click();
  const payment = page.locator('.payment-page');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(payment.getByRole('heading', { name: /Confirming your payment/ })).toBeVisible();
  await expect(payment.getByRole('heading', { name: 'Your week is sorted.' })).toBeVisible();
  await expect(payment.getByRole('status')).toContainText('No real order has been placed');
  await payment.getByRole('button', { name: 'Track my order' }).click();
  await expect(payment).toContainText('Plate sticker codes appear when preparation begins');
  await page.screenshot({ path: 'test-results/mealhr-payment-confirmation-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/mealhr-payment-confirmation-desktop.png' });
  await payment.getByRole('button', { name: 'Close payment preview' }).click();
  await expect(page.getByLabel('Address & landmark')).toHaveValue('Samaru, beside the main market entrance');
});

test('empty checkout points customers back to the menu', async ({ page }) => {
  await page.goto('/checkout');
  await expect(page.getByRole('heading', { name: 'Your week is still open.' })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Explore the menu' })).toHaveAttribute('href', '/');
});
